export function generateAsciiBoard(chess: Chess): string {
  const board = chess.board();
  const rows: string[] = [];
  rows.push('  +------------------------+');
  for (let r = 0; r < 8; r++) {
    const rankNum = 8 - r;
    const rowCells = board[r].map(cell => {
      if (!cell) return ' . ';
      const symbol = cell.color === 'w' ? cell.type.toUpperCase() : cell.type.toLowerCase();
      return ` ${symbol} `;
    });
    rows.push(`${rankNum} |${rowCells.join('')}|`);
  }
  rows.push('  +------------------------+');
  rows.push('     a  b  c  d  e  f  g  h');
  return rows.join('\n');
}

export function buildSystemPrompt(
  style: GrandmasterStyle,
  customPrompt?: string,
  opponentConfig?: PlayerConfig
): string {
  const preset = GRANDMASTER_PRESETS[style] || GRANDMASTER_PRESETS.kasparov;
  let opponentInfo = '';
  if (opponentConfig) {
    const oppPreset = GRANDMASTER_PRESETS[opponentConfig.style];
    if (opponentConfig.type === 'human') {
      opponentInfo = `Твой соперник в этой партии: Человек (имя: "${opponentConfig.name}"). Учитывай человеческие ошибки, цейтнот и психологию.`;
    } else if (oppPreset) {
      opponentInfo = `Твой соперник в этой партии: ${oppPreset.name} (${oppPreset.title}). ${oppPreset.description}`;
    }
  }

  return `Ты — элитный шахматный гроссмейстер мирового уровня. Твоя цель — победить соперника, играя на высочайшем уровне тактической и позиционной глубины.

${preset.promptFlavor}
${opponentInfo ? `\n# ИНФОРМАЦИЯ О ТВОЕМ СОПЕРНИКЕ:\n${opponentInfo}\nУчитывай стиль и слабости оппонента в своих рассуждениях!\n` : ''}
${customPrompt ? `\nДополнительные инструкции игрока:\n${customPrompt}\n` : ''}

# АЛГОРИТМ ТВОЕГО МЫШЛЕНИЯ (Chain-of-Thought):
В каждом ходе ты ОБЯЗАН провести структурированный глубокий анализ:
1. **Угрозы и безопасность**: Атакован ли мой король? Есть ли прямые угрозы взятия, шахов, вилок или связок от соперника на последнем ходу?
2. **Тактические мотивы**: Ищи слабости у соперника (незащищенные фигуры, плохая позиция короля, вскрытые линии, перегруженные защитники).
3. **Стратегический план**: Контроль центра, гармония фигур, создание проходных пешек, ограничение фигур соперника.
4. **Кандидатные ходы и расчет**: Рассмотри 2-3 хода из списка легальных ходов. Рассчитай ответы соперника на 2-3 полухода вперед.
5. **Выбор сильнейшего хода**: Выбери один наилучший ход.

# ЖЕСТКИЙ ФОРМАТ ОТВЕТА:
- Рассуждения помести внутрь <think>...</think>.
- После рассуждений ОБЯЗАТЕЛЬНО добавь короткую живую реплику оппоненту (1-2 предложения в твоем стиле/характере, с трэштоком или колкостью) в теге <comment>Твоя реплика оппоненту</comment>.
- В самом конце ответа выведи выбранный ход СТРОГО в теге <move>ХОД</move> (например: <move>Nf3</move> или <move>e2e4</move>).
- ВНИМАНИЕ: Ход ОБЯЗАН быть строго из предоставленного списка легальных ходов!

Пример идеального ответа:
<think>
1. Анализ угроз: Соперник напал на коня d4 ходом e5.
2. План: Отступить конем на f3 с сохранением контроля центра.
3. Решение: Nf3.
</think>
<comment>Лошадью хожу, блядь, смотри и учись!</comment>
<move>Nf3</move>`;
}

export function buildUserMovePrompt(
  chess: Chess,
  color: PieceColor,
  retryReason?: string,
  opponentConfig?: PlayerConfig,
  lastOpponentComment?: string
): string {
  const colorName = color === 'w' ? 'Белые (White)' : 'Черные (Black)';
  const opponentColor = color === 'w' ? 'Черных' : 'Белых';
  const oppPreset = opponentConfig ? GRANDMASTER_PRESETS[opponentConfig.style] : null;
  const oppName = opponentConfig 
    ? (opponentConfig.type === 'human' ? `${opponentConfig.name} (Человек)` : `${oppPreset?.name || opponentConfig.name}`)
    : opponentColor;
  const fen = chess.fen();
  const asciiBoard = generateAsciiBoard(chess);
  const pgn = chess.pgn() || '(Начало партии, 1-й ход)';
  const moveNumber = Math.floor(chess.history().length / 2) + 1;

  const legalMovesVerbose = chess.moves({ verbose: true });
  const legalMovesSan = chess.moves();
  const legalMovesUci = legalMovesVerbose.map(m => `${m.from}${m.to}${m.promotion || ''}`);

  const isCheck = chess.inCheck();
  const history = chess.history();
  const lastOpponentMove = history.length > 0 ? history[history.length - 1] : 'нет';

  let prompt = '';

  if (retryReason) {
    prompt += `🚨 ВНИМАНИЕ! ОШИБКА ПРЕДЫДУЩЕЙ ПОПЫТКИ!
${retryReason}
Твой предложенный ход был НЕВАЛИДЕН или НЕЛЕГАЛЕН!
Ты ОБЯЗАН выбрать ход ТОЛЬКО из списка легальных ходов ниже!\n\n`;
  }

  prompt += `Сейчас ход номер ${moveNumber}. Твой цвет: ${colorName}.
Твой соперник (${opponentColor}): ${oppName}.
Последний ход соперника: ${lastOpponentMove}.
${lastOpponentComment ? `💬 Реплика соперника на этом ходу: «${lastOpponentComment}»\n(Можешь ответить ему и подколоть в своем теге <comment>... </comment>!)` : ''}
${isCheck ? '⚠️ ТВОЙ КОРОЛЬ ПОД ШАХОМ! Ты обязан защититься от шаха!' : ''}

Текущая позиция на доске (FEN):
\`\`\`
${fen}
\`\`\`

Визуализация доски (с точки зрения Белых снизу 1-8, слева направо a-h):
\`\`\`
${asciiBoard}
\`\`\`
(Заглавные буквы P, N, B, R, Q, K — Белые; строчные p, n, b, q, r, k — Черные)

История партии (PGN):
${pgn}

ДОСТУПНЫЕ ЛЕГАЛЬНЫЕ ХОДЫ (выбери СТРОГО один из них!):
В формате SAN: [ ${legalMovesSan.join(', ')} ]
В формате UCI: [ ${legalMovesUci.join(', ')} ]

Проанализируй позицию в тегах <think>...</think> и выведи выбранный ход в тегах <move>ХОД</move>.`;

  return prompt;
}
